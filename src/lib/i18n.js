/** Como t(), sustituyendo {marcadores}: tf('tabla.filas', 'en', { n: 3 }) -> '3 rows' */
export function tf(clave, lang = 'es', vars = {}) {
    return t(clave, lang).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
