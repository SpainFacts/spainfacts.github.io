const sustituir = (texto, pares) => (pares ?? []).reduce((t, [a, b]) => t.split(a).join(b), texto ?? '');

/** { nombre, unidad, fuente } traducidos para una fila de internacional_ultimo o de
 *  internacional_resumen. Los indicadores de Eurostat (ambito = 'europa') buscan primero
 *  la clave 'europa:<indicador_id>', porque el mismo id puede tener otra definición en el
 *  Banco Mundial (paro de 15 a 74 años frente a paro de 15 años o más). */
export function textosIndicador(fila, lang) {
    if (!fila || lang === 'es') return { nombre: fila?.nombre, unidad: fila?.unidad, fuente: fila?.fuente };
    const dic = INDICADORES_INT[lang] ?? {};
    const e = (fila.ambito === 'europa' ? dic[`europa:${fila.indicador_id}`] : undefined) ?? dic[fila.indicador_id];
    const nombre = Array.isArray(e) ? e[0] : e ?? fila.nombre;
    const unidad = Array.isArray(e) ? e[1] : sustituir(fila.unidad, UNIDADES[lang]);
    return { nombre, unidad, fuente: sustituir(fila.fuente, FUENTES[lang]) };
}
